ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rasterlab.core import (
    Renderer,
    Mesh,
    look_at,
    perspective,
    clip_polygon,
    coverage_mask,
)
from rasterlab.scenes import torus, plane, checker, rotation


def save(path, array):
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(array).save(path)


def write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2) + "\n", encoding="utf-8", newline="\n")


def export_obj(path, mesh):
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# Procedural torus source; generated by src/rasterlab/scenes.py\n")
        for v in mesh.positions:
            f.write("v " + " ".join(f"{x:.9f}" for x in v) + "\n")
        for uv in mesh.uv:
            f.write("vt " + " ".join(f"{x:.9f}" for x in uv) + "\n")
        for n in mesh.normals:
            f.write("vn " + " ".join(f"{x:.9f}" for x in n) + "\n")
        for face in mesh.triangles:
            f.write("f " + " ".join(f"{i+1}/{i+1}/{i+1}" for i in face) + "\n")


def hero(width, height, angle=0.4, detail=64):
    renderer = Renderer(width, height)
    y, x = np.indices((height, width))
    glow = np.exp(
        -(
            ((x - width * 0.5) / (width * 0.5)) ** 2
            + ((y - height * 0.5) / (height * 0.6)) ** 2
        )
        * 2
    )
    renderer.color += glow[:, :, None] * np.array([0.035, 0.025, 0.075])
    view = look_at([3.5, 2.5, 5.5], [0, 0, 0])
    projection = perspective(np.radians(43), width / height, 0.2, 30)
    ground = checker(256, 8, ((0.05, 0.065, 0.10), (0.10, 0.11, 0.16)))
    renderer.draw(plane(4, -1.15), np.eye(4), view, projection, ground, lit=True)
    renderer.draw(
        torus(around=detail, tube=detail // 2),
        rotation(angle),
        view,
        projection,
        checker(),
        lit=True,
    )
    return renderer


def clip_vertices(screen, z, w, width, height, uv=None):
    screen = np.asarray(screen, dtype=float)
    ndc = np.column_stack(
        [
            screen[:, 0] * 2 / width - 1,
            1 - screen[:, 1] * 2 / height,
            np.broadcast_to(z, 3),
        ]
    )
    w = np.broadcast_to(w, 3)
    uv = (
        np.array([[0, 0], [1, 0], [0, 1]], dtype=float)
        if uv is None
        else np.asarray(uv)
    )
    return np.column_stack([ndc * w[:, None], w, uv, np.tile([0, 0, 1], (3, 1))])


def build(out, movie=False, quick=False):
    docs = out / "docs"
    images = docs / "renders"
    images.mkdir(parents=True, exist_ok=True)
    results = out / "results"
    results.mkdir(exist_ok=True)
    assets = out / "assets"
    assets.mkdir(exist_ok=True)
    frame = hero(960, 660)
    save(images / "hero.png", frame.image())
    export_obj(assets / "torus.obj", torus())
    save(assets / "checker.png", np.round(checker() * 255).astype(np.uint8))
    comparison = []
    for mode in ["affine", "perspective"]:
        r = Renderer(800, 560)
        r.draw(
            plane(2, 0),
            np.eye(4),
            look_at([2.8, 2.3, 3.8], [0, 0, 0]),
            perspective(np.radians(47), 800 / 560, 0.2, 30),
            checker(colors=((0.95, 0.72, 0.27), (0.22, 0.1, 0.38))),
            mode,
            False,
        )
        save(images / f"{mode}.png", r.image())
        comparison.append(r)
    overlap = np.isfinite(comparison[0].depth) & np.isfinite(comparison[1].depth)
    uv_error = np.linalg.norm(
        comparison[0].uv[overlap] - comparison[1].uv[overlap], axis=1
    )
    # Near-plane and side-plane clipping diagnostic in view coordinates.
    r = Renderer(800, 560)
    mesh = Mesh(
        np.array([[-0.8, -0.7, -0.4], [1.1, -0.65, -2.4], [0, 1.1, -2.0]]),
        np.tile([0, 0, 1], (3, 1)),
        np.array([[0, 0], [2, 0], [1, 2]]),
        np.array([[0, 1, 2]]),
    )
    projection = perspective(np.radians(65), 800 / 560, 1, 10)
    clip = np.column_stack([mesh.positions, np.ones(3)]) @ projection.T
    clipped = clip_polygon(np.column_stack([clip, mesh.uv, mesh.normals]))
    r.draw(mesh, np.eye(4), np.eye(4), projection, checker(), lit=False)
    save(images / "clipping.png", r.image())
    write_json(
        results / "clipping.json",
        {
            "near": 1,
            "far": 10,
            "input_view_positions": mesh.positions.tolist(),
            "clip_input": clip.tolist(),
            "clip_output": clipped[:, :4].tolist(),
            "polygon_vertices_after_clipping": len(clipped),
            "rasterized_fan_triangles": max(len(clipped) - 2, 0),
        },
    )
    # Shared-edge diagnostic: two colored triangles partition an exact pixel square.
    width, height = 800, 560
    square = np.array([[180, 60], [620, 60], [620, 500], [180, 500]], dtype=float)
    ma = coverage_mask(square[[0, 1, 2]], width, height)
    mb = coverage_mask(square[[0, 2, 3]], width, height)
    image = np.broadcast_to([18, 14, 30], (height, width, 3)).copy().astype(np.uint8)
    image[ma] = [69, 206, 216]
    image[mb] = [169, 83, 224]
    save(images / "shared-edge.png", image)
    # Overlapping depth layers: draw order deliberately disagrees with visibility.
    depth = Renderer(width, height)
    depth.triangle(
        clip_vertices([[100, 440], [700, 440], [400, 50]], 0.5, 1, width, height),
        np.array([[[0.25, 0.8, 0.88]]]),
    )
    depth.triangle(
        clip_vertices([[90, 90], [710, 90], [400, 520]], -0.35, 1, width, height),
        np.array([[[0.69, 0.29, 0.9]]]),
    )
    depth.triangle(
        clip_vertices([[60, 480], [740, 480], [400, 130]], 0.8, 1, width, height),
        np.array([[[0.98, 0.67, 0.22]]]),
    )
    save(images / "occlusion.png", depth.image())
    valid = np.isfinite(depth.depth)
    heat = np.zeros((height, width, 3))
    heat[:] = [0.07, 0.055, 0.12]
    heat[valid] = np.stack(
        [1 - depth.depth[valid], 0.25 + depth.depth[valid] * 0.6, depth.depth[valid]],
        axis=1,
    )
    save(images / "depth.png", np.round(heat * 255).astype(np.uint8))
    checks = {
        "shared_edge_overlap_pixels": int((ma & mb).sum()),
        "shared_edge_covered_pixels": int((ma | mb).sum()),
        "expected_square_pixels": 440 * 440,
        "affine_vs_perspective_mean_uv_distance": float(uv_error.mean()),
        "affine_vs_perspective_max_uv_distance": float(uv_error.max()),
        "comparison_covered_pixels": int(overlap.sum()),
        "hero_stats": frame.stats,
    }
    write_json(results / "diagnostics.json", checks)
    # One untimed warmup precedes independent whole-frame samples. No GPU is involved.
    hero(480, 320, detail=32)
    timings = []
    for i in range(3 if quick else 12):
        start = time.perf_counter_ns()
        f = hero(480, 320, detail=32)
        timings.append(
            {
                "sample": i,
                "width": 480,
                "height": 320,
                "input_triangles": f.stats["input_triangles"],
                "elapsed_ms": (time.perf_counter_ns() - start) / 1e6,
            }
        )
    with (results / "frame_timings.csv").open(
        "w", newline="", encoding="utf-8"
    ) as file:
        writer = csv.DictWriter(file, fieldnames=list(timings[0]))
        writer.writeheader()
        writer.writerows(timings)
    metadata = {
        "recorded_at_utc": datetime.now(timezone.utc).isoformat(),
        "python": platform.python_version(),
        "numpy": np.__version__,
        "os": platform.system(),
        "architecture": platform.machine(),
        "implementation": "CPU Python/NumPy triangle renderer; no GPU or graphics engine",
        "timed_scope": "Whole hero frame: mesh/texture generation, matrices, clipping, rasterization and shading; excludes PNG encoding",
        "samples": len(timings),
        "warmup_frames": 1,
        "median_frame_ms": float(np.median([t["elapsed_ms"] for t in timings])),
        "core_sha256": hashlib.sha256(
            (ROOT / "src/rasterlab/core.py").read_bytes()
        ).hexdigest(),
    }
    write_json(results / "metadata.json", metadata)
    write_json(
        results / "image_sha256.json",
        {
            p.relative_to(out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(images.glob("*.png"))
        },
    )
    if movie:
        render_movie(out)
    report(out, checks, metadata)
    print(
        json.dumps(
            {
                "output": str(out),
                "median_frame_ms": metadata["median_frame_ms"],
                "diagnostics": checks,
            }
        )
    )


def render_movie(out):
    if not shutil.which("ffmpeg"):
        raise RuntimeError("FFmpeg on PATH is required for --movie")
    frames = out / "build/turntable-frames"
    frames.mkdir(parents=True, exist_ok=True)
    recordings = out / "docs/recordings"
    recordings.mkdir(exist_ok=True)
    for i in range(48):
        save(
            frames / f"{i:04d}.png",
            hero(640, 420, angle=i / 48 * 2 * np.pi, detail=40).image(),
        )
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-loglevel",
            "error",
            "-framerate",
            "12",
            "-i",
            str(frames / "%04d.png"),
            "-c:v",
            "libx264",
            "-crf",
            "18",
            "-pix_fmt",
            "yuv420p",
            "-movflags",
            "+faststart",
            str(recordings / "turntable.mp4"),
        ],
        check=True,
    )
    write_json(
        recordings / "turntable-provenance.json",
        {
            "type": "Synthetic scene rendered frame-by-frame by the CPU renderer",
            "frames": 48,
            "frames_per_second": 12,
            "width": 640,
            "height": 420,
            "mesh_around": 40,
            "mesh_tube": 20,
            "camera": "Fixed; model rotates once through 2*pi",
            "script": "scripts/render_study.py --movie",
            "not_screen_recording": True,
            "video_sha256": hashlib.sha256(
                (recordings / "turntable.mp4").read_bytes()
            ).hexdigest(),
            "source_sha256": {
                name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
                for name in [
                    "src/rasterlab/core.py",
                    "src/rasterlab/scenes.py",
                    "scripts/render_study.py",
                ]
            },
        },
    )


